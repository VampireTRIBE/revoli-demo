import { useQuery } from '@tanstack/react-query';
import { http } from '../../api/http';
import type { TblReadsResponse } from '../../types/reads';
import './tbl-reads.css';

interface Props { client: string; section: 'Media' | 'Creative' | 'Consumer' | 'Competition'; year?: number; month?: number; }

/** One approved hero per tab; section-specific signed notes render in SectionAnatomy.
 * No editorial text is fabricated from dashboard numbers. */
export function TblReadsStrip({ client, section, year, month }: Props) {
  const query = useQuery({
    queryKey: ['tbl-reads', client, section, year, month],
    queryFn: async () => (await http.get<{ data: TblReadsResponse }>('/reads', { params: { client, section, year, month } })).data.data,
    enabled: Boolean(client && year && month !== undefined),
  });
  if (!year || month === undefined) return null;
  if (query.isLoading) return <div className="v2-highlights-loading" role="status">Checking signed Highlights...</div>;
  const approved = query.data?.reads ?? [];
  const firstFill=query.data?.firstFill??[];
  if (!approved.length && !query.isError && firstFill.length) return <section className="v2-first-fill" aria-label="Imported TBL first-fill commentary">
    <p className="v2-hero-eyebrow">Imported TBL commentary · {query.data?.firstFillPeriod} · sign-off not recorded</p>
    <p className="v2-first-fill-hero">{firstFill[0]?.bullet}</p>
    {firstFill.slice(1).map(read=><p key={read.order}>{read.bullet}</p>)}
    <small>Source: {query.data?.sourceFile}. Annual context is not a selected-month Highlight. Signed section Highlights are still awaiting approval.</small>
  </section>;
  if (query.isError || !approved.length) return <div className="v2-highlights-pending" role="status"><span className="v2-awaiting-dot" /> <b>HIGHLIGHTS PENDING</b> · Awaiting explicit TBL sign-off for {client} {section.toLowerCase()} · {month ? `${year}-${String(month).padStart(2, '0')}` : year}</div>;
  const hero = approved.find((read)=>/^(hero|tab|highlights this month)$/i.test(read.linkedCard.trim())) ?? approved[0]!;
  return <section className="v2-highlights-hero" aria-label="Signed highlight this month">
    <p className="v2-hero-eyebrow">Highlights this month · {query.data?.period} · signed</p>
    <h2>{hero.bullet}</h2>
    <p className="v2-hero-source">Imported from {query.data?.sourceFile}. Editorial text is not generated by the engine.</p>
  </section>;
}
