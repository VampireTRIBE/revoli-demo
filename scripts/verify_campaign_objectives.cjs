/** Executes the actual ranking and aggregation functions, without React or a database. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
function load(relative, extra = '', deps = {}) {
  const file = path.join(root, relative);
  const out = ts.transpileModule(fs.readFileSync(file,'utf8') + '\n' + extra, {compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
  const sandbox = {exports:{},require:(id)=>{if(!(id in deps))throw Error(`Unexpected dependency: ${id}`);return deps[id]}};
  vm.runInNewContext(out,sandbox,{filename:file,timeout:5000});
  return sandbox.exports;
}
const {campaignResult,groupCampaignRankings,objective} = load('client/src/features/media/utils/campaign-ranking.ts');
const row = (campaign, o, fields={}) => ({platform:'Meta Ads',campaign,objective:o,spend:100,...fields});
const awarenessViews=row('view ad','Awareness',{views:2000,claims:99});
const awarenessImpressions=row('impression ad','Awareness',{impressions:5000,claims:999});
const awarenessMissing=row('unknown ad','Awareness',{claims:1000});
const conversion=row('conversion ad','Conversion',{claims:4.5});
const traffic=row('traffic ad','Traffic',{clicks:20,claims:100});
const unknown=row('PMAX_conversion_traffic',null,{claims:10});
assert.equal(campaignResult(awarenessViews).measure,'views');
assert.equal(campaignResult(awarenessViews).cost,50);
assert.equal(campaignResult(awarenessImpressions).measure,'impressions');
assert.equal(campaignResult(awarenessImpressions).cost,20);
assert.equal(campaignResult(awarenessMissing).cost,null);
assert.equal(campaignResult(traffic).cost,5);
assert.equal(campaignResult(conversion).count,4.5);
assert.equal(campaignResult(unknown),null);
assert.equal(objective(unknown),'Not supplied');
assert.equal(campaignResult(row('zero views','Awareness',{views:0,claims:10})).cost,null);
assert.equal(campaignResult(row('bad spend','Conversion',{claims:5,spend:NaN})).cost,null);
assert.equal(campaignResult(row('zero spend','Traffic',{clicks:10,spend:0})).cost,0);
const groups=groupCampaignRankings([awarenessViews,awarenessImpressions,awarenessMissing,conversion,traffic,unknown,row('cheaper view','Awareness',{views:4000}),row('google view','Awareness',{platform:'Google Ads',views:5000})],'Awareness');
assert.equal(groups.ranked.length,3,'different measures and platforms are isolated');
assert.equal(groups.unranked.length,1);
assert.equal(groups.ranked[0].rows[0].campaign,'cheaper view');
assert.equal(groups.ranked.reduce((s,g)=>s+g.rows.length,0),4);
const {aggregateCampaignRows}=load('server/src/modules/media/services/media-analytics.service.ts','export {aggregateCampaignRows};',{'../calculations/media-calculations.js':{},'./media-data.service.js':{},'./media-supplements.service.js':{}});
const agg=aggregateCampaignRows([row('same','Awareness',{views:1000,impressions:2000,shortName:'A',thumbnailFile:'a.png'}),row('same','Awareness',{impressions:3000,shortName:'B',thumbnailFile:'b.png'})])[0];
assert.equal(agg.spend,200);
assert.equal(agg.views,undefined,'never sum known views against spend containing missing views');
assert.equal(agg.impressions,5000);
assert.equal(agg.shortName,null);
assert.equal(agg.thumbnailFile,null);
assert.equal(aggregateCampaignRows([row('same','Awareness'),row('same','Conversion')])[0].objective,null);
const {optionalNumber}=load('server/src/modules/media/utils/value-utils.ts');
assert.equal(optionalNumber('n/a'),null);
assert.equal(optionalNumber('0'),0);
assert.equal(optionalNumber('1,234.5'),1234.5);
console.log('PASS campaign calculation regression: objective/platform/measure separation, cost formulas, missing denominators, zero spend, fractional conversions, strict aggregation and conflicting metadata.');
